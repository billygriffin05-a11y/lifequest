export type IconName = keyof typeof ICONS;

export function PixelIcon({ name, className }: { name: IconName; className?: string }) {
  const rows = ICONS[name];
  return (
    <svg viewBox="0 0 12 12" shapeRendering="crispEdges" aria-hidden="true" focusable="false" className={className} data-icon={name}>
      {rows.flatMap((row, y) =>
        [...row].map((ch, x) =>
          ch === "." ? null : <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} className={FILLS[ch as Pixel]} />,
        ),
      )}
    </svg>
  );
}
